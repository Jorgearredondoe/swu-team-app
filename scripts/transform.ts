import { SET_CODES, type Card, type Rarity, type SetCode } from '../src/lib/types.ts';

type Named = { data: { attributes: { name: string } } | null };
type ArtAsset = {
  data: { attributes: { url: string; formats?: { card?: { url?: string } } | null } } | null;
};

export type RawCard = {
  id: number;
  attributes: {
    title: string;
    subtitle: string | null;
    cardNumber: number;
    artFront: ArtAsset;
    type: Named;
    rarity: Named;
    expansion: { data: { attributes: { code: string } } | null };
    variantTypes: { data: { attributes: { name: string } }[] };
    variantOf: { data: unknown | null };
  };
};

export type RawPage = { data: RawCard[] };

const RARITIES: readonly Rarity[] = ['Rare', 'Legendary'];

function isSetCode(code: string | undefined): code is SetCode {
  return (SET_CODES as readonly string[]).includes(code ?? '');
}

function isRarity(name: string | undefined): name is Rarity {
  return (RARITIES as readonly string[]).includes(name ?? '');
}

function imageUrlOf(art: ArtAsset): string {
  const attrs = art.data?.attributes;
  return attrs?.formats?.card?.url ?? attrs?.url ?? '';
}

function isBaseVariant(card: RawCard): boolean {
  const { variantTypes, variantOf } = card.attributes;
  return variantOf.data === null && variantTypes.data.some((v) => v.attributes.name === 'Standard');
}

/** Converts raw API pages into the base R/L catalog: no variants, deduplicated, sorted. */
export function transformCards(page: RawPage): Card[] {
  const byId = new Map<string, Card>();
  for (const raw of page.data) {
    const a = raw.attributes;
    const setCode = a.expansion.data?.attributes.code;
    const rarity = a.rarity.data?.attributes.name;
    if (!isSetCode(setCode) || !isRarity(rarity) || !isBaseVariant(raw)) continue;
    const id = `${setCode}-${a.cardNumber}`;
    if (byId.has(id)) continue;
    byId.set(id, {
      id,
      setCode,
      number: a.cardNumber,
      name: a.title,
      subtitle: a.subtitle ?? null,
      rarity,
      type: a.type.data?.attributes.name ?? 'Unknown',
      imageUrl: imageUrlOf(a.artFront),
    });
  }
  return [...byId.values()].sort(
    (x, y) => SET_CODES.indexOf(x.setCode) - SET_CODES.indexOf(y.setCode) || x.number - y.number,
  );
}

const lit = (value: string | null): string =>
  value === null ? 'null' : `'${value.replaceAll("'", "''")}'`;

/**
 * Upsert clause shared by the seed and its pgTAP test. `id` is deliberately NOT updated:
 * stock.card_id references it without ON UPDATE CASCADE, so rewriting an id would break
 * (or orphan) members' stock. The id stays whatever the row was first inserted with.
 */
export const SEED_CONFLICT_CLAUSE = [
  'on conflict (set_code, card_number) do update set',
  '  name = excluded.name,',
  '  subtitle = excluded.subtitle,',
  '  rarity = excluded.rarity,',
  '  card_type = excluded.card_type,',
  '  image_url = excluded.image_url;',
].join('\n');

/** Idempotent seed: re-running updates changed fields and never duplicates (set_code, card_number). */
export function buildSeedSql(cards: Card[]): string {
  const rows = cards.map(
    (c) =>
      `(${lit(c.id)}, ${lit(c.setCode)}, ${c.number}, ${lit(c.name)}, ${lit(c.subtitle)}, ${lit(c.rarity)}, ${lit(c.type)}, ${lit(c.imageUrl)})`,
  );
  return [
    '-- GENERATED by scripts/seed-cards.ts from supabase/seed/cards.json. Do not edit by hand.',
    'insert into public.cards (id, set_code, card_number, name, subtitle, rarity, card_type, image_url) values',
    rows.join(',\n'),
    SEED_CONFLICT_CLAUSE,
    '',
  ].join('\n');
}

export type CatalogReport = {
  counts: Record<SetCode, Record<Rarity, number>>;
  anomalies: string[];
};

/** Per-set R/L counts plus anomalies worth a human look (empty sets, missing images). */
export function summarizeCatalog(cards: Card[]): CatalogReport {
  const counts = Object.fromEntries(
    SET_CODES.map((set) => [set, { Rare: 0, Legendary: 0 }]),
  ) as CatalogReport['counts'];
  const anomalies: string[] = [];
  for (const card of cards) {
    counts[card.setCode][card.rarity] += 1;
    if (card.imageUrl === '') anomalies.push(`Card ${card.id} has no image url`);
  }
  for (const set of SET_CODES) {
    if (counts[set].Rare + counts[set].Legendary === 0) anomalies.push(`No cards for set ${set}`);
  }
  return { counts, anomalies };
}
